/**
 * Comly Network — static build
 * Usage: node build/build.mjs [--site=<id>]
 * Output: dist/<site-id>/  (ready for `wrangler pages deploy`)
 */
import { cp, mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { sites, brand, plans, addons } from '../sites/registry.mjs';
import { renderSite, renderNotFound, renderGone } from './render.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const OUT = path.join(root, 'dist');
const ASSETS = path.join(root, 'assets');
const FUNCTIONS = path.join(root, 'functions');

const siteArg = process.argv.find((arg) => arg.startsWith('--site='));
const wanted = siteArg ? siteArg.split('=')[1] : null;
const targets = wanted ? sites.filter((site) => site.id === wanted) : sites;

if (!targets.length) {
  console.error(`Unknown site: ${wanted}`);
  process.exit(1);
}

const SECURITY_HEADERS = `/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: SAMEORIGIN
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: geolocation=(), microphone=(), camera=()
/assets/*
  Cache-Control: public, max-age=31536000, immutable
`;

function sitemapEntries(site, pages) {
  const byKey = {};
  for (const page of pages) {
    byKey[page.key] = byKey[page.key] || {};
    byKey[page.key][page.lang] = `https://${site.host}${page.path}`;
  }
  const rows = [];
  for (const key of Object.keys(byKey)) {
    const pair = byKey[key];
    for (const lang of ['ar', 'en']) {
      if (!pair[lang]) continue;
      rows.push(
        `  <url><loc>${pair[lang]}</loc><xhtml:link rel="alternate" hreflang="ar" href="${pair.ar}"/><xhtml:link rel="alternate" hreflang="en" href="${pair.en}"/><xhtml:link rel="alternate" hreflang="x-default" href="${pair.ar}"/><changefreq>weekly</changefreq></url>`
      );
    }
  }
  return rows.join('\n');
}

const startedAt = Date.now();
for (const site of targets) {
  const outDir = path.join(OUT, site.id);
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });

  await cp(ASSETS, path.join(outDir, 'assets'), { recursive: true });
  await cp(FUNCTIONS, path.join(outDir, 'functions'), { recursive: true });

  const siteConfig = {
    id: site.id,
    host: site.host,
    role: site.role,
    colors: site.colors,
    network: sites.map((s) => ({ id: s.id, host: s.host }))
  };
  await writeFile(
    path.join(outDir, 'functions', '_lib', 'site-config.js'),
    `/* Generated by build/build.mjs — do not edit */\nexport const SITE = ${JSON.stringify(siteConfig, null, 2)};\n`,
    'utf8'
  );

  const pages = renderSite({ site, brand, sites, plans, addons });

  for (const page of pages) {
    const rel = page.path === '/' ? 'index.html' : path.join(page.path.replace(/^\/|\/$/g, ''), 'index.html');
    const file = path.join(outDir, rel);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, page.html, 'utf8');
  }

  await writeFile(path.join(outDir, '404.html'), renderNotFound({ site }), 'utf8');
  await writeFile(path.join(outDir, '410.html'), renderGone({ site }), 'utf8');

  /* sitemap */
  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${sitemapEntries(site, pages)}\n</urlset>\n`;
  await writeFile(path.join(outDir, 'sitemap.xml'), sitemap, 'utf8');

  /* robots */
  await writeFile(
    path.join(outDir, 'robots.txt'),
    `User-agent: *\nAllow: /\n\nSitemap: https://${site.host}/sitemap.xml\n`,
    'utf8'
  );

  /* headers */
  await writeFile(path.join(outDir, '_headers'), SECURITY_HEADERS, 'utf8');

  /* routes.json — keep static pages off the Functions quota */
  const excludes = new Set(['/', '/assets/*', '/sitemap.xml', '/robots.txt', '/favicon.ico', '/404.html', '/410.html']);
  for (const page of pages) {
    excludes.add(page.path);
    if (page.path !== '/' && page.path.endsWith('/')) excludes.add(page.path.slice(0, -1));
  }
  await writeFile(
    path.join(outDir, '_routes.json'),
    JSON.stringify({ version: 1, include: ['/*'], exclude: [...excludes] }, null, 2),
    'utf8'
  );

  console.log(`✔ ${site.id.padEnd(8)} ${String(pages.length).padStart(2)} pages → dist/${site.id}`);
}

console.log(`\nDone: ${targets.length} site(s) in ${Date.now() - startedAt}ms`);
