/**
 * Deploy one or more sites to Cloudflare Pages with shared D1/KV bindings.
 *
 * Usage:
 *   node scripts/deploy.mjs n3
 *   node scripts/deploy.mjs commly n3 n4 n6 n7 n8 n9
 *
 * Pages discovers Functions from the working directory, so deployment must run
 * from the repository root. Pages also only reads ./wrangler.toml (no --config),
 * so this script temporarily writes a per-site config and always restores it.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const configPath = path.join(root, 'wrangler.toml');
const wrangler = path.join(root, 'node_modules', 'wrangler', 'bin', 'wrangler.js');
const original = await readFile(configPath, 'utf8');

const requested = process.argv.slice(2);
const sites = requested.length ? requested : ['commly', 'n3', 'n4', 'n6', 'n7', 'n8', 'n9'];
const project = (site) => (site === 'commly' ? 'comm-ly' : `comly-${site}`);

function configFor(site) {
  return `# Generated by scripts/deploy.mjs for ${site} — do not edit by hand.
name = "${project(site)}"
pages_build_output_dir = "dist/${site}"
compatibility_date = "2026-10-01"

[[d1_databases]]
binding = "DB"
database_name = "comly"
database_id = "417f6acd-60fa-4f88-a85f-f85a05fe0335"

[[kv_namespaces]]
binding = "CACHE"
id = "e86ee4ad80904265a273d6a4d083bef3"
`;
}

const failures = [];
try {
  for (const site of sites) {
    console.log(`\n=== Deploying ${project(site)} (dist/${site}) ===`);
    await writeFile(configPath, configFor(site), 'utf8');
    const result = spawnSync(
      process.execPath,
      [wrangler, 'pages', 'deploy', `dist/${site}`,
        '--project-name', project(site),
        '--branch', 'main',
        '--commit-dirty=true',
        '--commit-message', `Deploy ${project(site)} — network tools + design system`],
      { cwd: root, stdio: 'inherit' }
    );
    if (result.status !== 0) failures.push(site);
  }
} finally {
  await writeFile(configPath, original, 'utf8');
  console.log('\nRestored original wrangler.toml');
}

if (failures.length) {
  console.error(`\nFailed deployments: ${failures.join(', ')}`);
  process.exitCode = 1;
} else {
  console.log(`\nAll deployments succeeded: ${sites.join(', ')}`);
}
